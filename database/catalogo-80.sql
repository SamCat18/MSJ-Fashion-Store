  (select count(*) from public.products where is_active) as productos_activos,
  (select count(distinct brand_id) from public.products where is_active and brand_id is not null) as marcas_con_productos,
  (select count(distinct collection_id) from public.collection_products) as colecciones_con_productos,
  (select count(*) from public.product_variants v join public.products p on p.id = v.product_id where p.is_active) as variantes;
